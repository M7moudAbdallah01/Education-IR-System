def setup_style(root):
    style = ttk.Style(root)
    style.theme_use("clam")
    style.configure("Treeview", rowheight=24, font=(FONT, 10), background="white",
                    fieldbackground="white", foreground="#3b2a18")
    style.configure("Treeview.Heading", font=(FONT, 10, "bold"), background=BTN,
                    foreground="white", relief="flat", padding=5)
    style.map("Treeview", background=[("selected", "#E3C9A3")],
              foreground=[("selected", "#3b2a18")])


def make_table(parent, columns, widths, height=10):
    frame = tk.Frame(parent, bg="white", highlightbackground=BORDER, highlightthickness=1)
    tree = ttk.Treeview(frame, columns=columns, show="headings", height=height)
    y_scroll = ttk.Scrollbar(frame, orient="vertical", command=tree.yview)
    x_scroll = ttk.Scrollbar(frame, orient="horizontal", command=tree.xview)
    tree.configure(yscrollcommand=y_scroll.set, xscrollcommand=x_scroll.set)

    for index, column in enumerate(columns):
        width = widths[index] if index < len(widths) else 120
        tree.heading(column, text=column)
        # Let columns expand with the table so no unused white area remains
        # on the right when the table is wider than the requested column widths.
        tree.column(column, width=width, minwidth=45,
                    anchor="w" if index == 0 else "center", stretch=True)

    tree.tag_configure("odd", background="#FBF5EC")
    tree.grid(row=0, column=0, sticky="nsew")
    y_scroll.grid(row=0, column=1, sticky="ns")
    x_scroll.grid(row=1, column=0, sticky="ew")
    frame.rowconfigure(0, weight=1)
    frame.columnconfigure(0, weight=1)
    return frame, tree


def fill(tree, rows):
    tree.delete(*tree.get_children())
    for index, row in enumerate(rows):
        tree.insert("", "end", values=row, tags=("odd",) if index % 2 else ())


