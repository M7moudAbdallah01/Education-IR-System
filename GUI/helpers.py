# Formatting helpers

def doc_order(doc):
    """Sort document names naturally (doc2 before doc10)."""
    parts = re.split(r"(\d+)", str(doc))
    return tuple(
        (0, int(part)) if part.isdigit() else (1, part.lower())
        for part in parts
    )


def fmt(value):
    """Format numeric values consistently in all tables."""
    try:
        number = float(value)
        return "0" if number == 0 else f"{number:.4f}"
    except (TypeError, ValueError):
        return str(value)


# Dataset loading

def _read_matrix(path, cast=float):
    """Read a term-by-document CSV matrix."""
    with open(path, encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)

        if not reader.fieldnames or len(reader.fieldnames) < 2:
            raise ValueError(f"Invalid matrix CSV format: {path}")

        if "term" not in reader.fieldnames:
            raise ValueError(f"Missing 'term' column in: {path}")

        documents = [name for name in reader.fieldnames if name != "term"]
        matrix = {}

        for row_number, row in enumerate(reader, start=2):
            term = (row.get("term") or "").strip()
            if not term:
                continue

            matrix[term] = {}
            for document in documents:
                raw_value = row.get(document, "")
                try:
                    numeric_value = float(raw_value) if raw_value not in (None, "") else 0.0
                    matrix[term][document] = cast(numeric_value)
                except (TypeError, ValueError) as error:
                    raise ValueError(
                        f"Invalid value in {os.path.basename(path)}, "
                        f"row {row_number}, document '{document}'."
                    ) from error

    return matrix, documents


def load_data(output_dir=None, dataset_path=None):
    """
    Load all generated files for one dataset.

    output_dir must contain the outputs generated by the project pipeline.
    dataset_path is optional and is displayed on the Home page.
    """
    output_dir = output_dir or DEFAULT_OUTPUT_DIR

    required_files = (
        "positional_index.json",
        "raw_tf.csv",
        "weighted_tf.csv",
        "tf-idf.csv",
        "normalized_tfidf.csv",
        "df_idf.csv",
        "doc_lengths.csv",
    )

    missing = [
        name for name in required_files
        if not os.path.isfile(os.path.join(output_dir, name))
    ]
    if missing:
        raise FileNotFoundError(
            "Missing generated output file(s) in "
            f"'{output_dir}': {', '.join(missing)}"
        )

    with open(
        os.path.join(output_dir, "positional_index.json"),
        encoding="utf-8"
    ) as file:
        index = json.load(file)

    raw_tf, documents = _read_matrix(
        os.path.join(output_dir, "raw_tf.csv"),
        int
    )
    weighted_tf, weighted_docs = _read_matrix(
        os.path.join(output_dir, "weighted_tf.csv")
    )
    tfidf, tfidf_docs = _read_matrix(
        os.path.join(output_dir, "tf-idf.csv")
    )
    normalized, normalized_docs = _read_matrix(
        os.path.join(output_dir, "normalized_tfidf.csv")
    )

    # All matrices must describe the same document collection.
    expected_docs = set(documents)
    for filename, matrix_docs in (
        ("weighted_tf.csv", weighted_docs),
        ("tf-idf.csv", tfidf_docs),
        ("normalized_tfidf.csv", normalized_docs),
    ):
        if set(matrix_docs) != expected_docs:
            raise ValueError(
                f"Document columns in {filename} do not match raw_tf.csv."
            )

    df = {}
    idf = {}
    with open(
        os.path.join(output_dir, "df_idf.csv"),
        encoding="utf-8-sig",
        newline=""
    ) as file:
        reader = csv.DictReader(file)
        required_columns = {"term", "DF", "IDF"}
        if not reader.fieldnames or not required_columns.issubset(reader.fieldnames):
            raise ValueError("df_idf.csv must contain term, DF, and IDF columns.")

        for row in reader:
            term = (row.get("term") or "").strip()
            if term:
                df[term] = int(float(row["DF"]))
                idf[term] = float(row["IDF"])

    lengths = {}
    with open(
        os.path.join(output_dir, "doc_lengths.csv"),
        encoding="utf-8-sig",
        newline=""
    ) as file:
        reader = csv.DictReader(file)
        required_columns = {"document", "vector_length"}
        if not reader.fieldnames or not required_columns.issubset(reader.fieldnames):
            raise ValueError(
                "doc_lengths.csv must contain document and vector_length columns."
            )

        for row in reader:
            document = (row.get("document") or "").strip()
            if document:
                lengths[document] = float(row["vector_length"])

    terms = sorted(raw_tf)

    return {
        "index": index,
        "terms": terms,
        "docs": sorted(documents, key=doc_order),
        "N": len(documents),
        "raw_tf": raw_tf,
        "weighted_tf": weighted_tf,
        "df": df,
        "idf": idf,
        "tfidf": tfidf,
        "normalized": normalized,
        "lengths": lengths,
        "output_dir": output_dir,
        "dataset_path": dataset_path or "",
    }


